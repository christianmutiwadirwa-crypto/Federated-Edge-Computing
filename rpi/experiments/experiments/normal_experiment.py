"""
=============================================================================
 normal_experiment.py
 Structural stub for the Normal baseline cybersecurity experiment.
=============================================================================
"""

from core.base_experiment import BaseExperiment
import time

class NormalExperiment(BaseExperiment):
    """
    Evaluates the baseline capabilities of the cyber intrusion detection system
    by collecting purely legitimate traffic generated by the physical edge devices,
    without executing any active cyber attacks.
    """

    def initialize(self) -> None:
        self._log_initialized()

    def run(self) -> None:
        self._log_started()
        
        pre_attack = self.experiment_config.get("pre_attack_duration", 5.0)
        self.logger.info(f"[{self.name}] Observing pre-attack baseline for {pre_attack}s...")
        time.sleep(pre_attack)

        attack_duration = self.experiment_config.get("attack_duration", 60.0)
        self.logger.info(f"[{self.name}] NORMAL BASELINE COLLECTION — Waiting for {attack_duration} seconds while physical traffic is collected.")
        
        # Sleep for the duration, catching KeyboardInterrupt so we can abort cleanly
        deadline = time.time() + attack_duration
        try:
            while time.time() < deadline:
                time.sleep(1.0)
        except KeyboardInterrupt:
            self.logger.warning(f"[{self.name}] Normal collection interrupted by user.")
        
        post_attack = self.experiment_config.get("post_attack_duration", 5.0)
        self.logger.info(f"[{self.name}] Observing post-attack baseline for {post_attack}s...")
        time.sleep(post_attack)
        
        self._log_completed()

    def cleanup(self) -> None:
        self.logger.info(f"[{self.name}] Normal baseline collection complete.")
        self._log_cleaned_up()
