from core.base_experiment import BaseExperiment
import os
import random
import socket
import struct
import time

def _build_malformed_packet() -> bytes:
    # Randomly select a length that is usually NOT 126 to trigger length/parsing errors
    # or occasionally 126 but with completely random garbage bytes to fail CRC and magic bytes.
    length = random.choice([random.randint(50, 125), random.randint(127, 200), 126])
    return os.urandom(length)

class PacketInjectionMalformedExperiment(BaseExperiment):
    """
    Evaluates the malformed and fabricated packet detection capabilities of the
    cyber intrusion detection system by inserting protocol packets that were not
    generated by a legitimate IIoT sensor.

    Injected packets may be fully synthetic, structurally valid but semantically
    incorrect (e.g. impossible sensor values), or partially corrupted to test CRC
    and integrity validation layers.

    Scientific purpose:
        Determine whether integrity features (crc_failure_count, crc_failure_rate,
        invalid_packet_count, invalid_packet_rate) and sensor-value outlier detection
        can reliably identify injected packets that bypass lower-level protocol
        validation while containing statistically implausible physical feature vectors.

    Framework integration:
        The ExperimentManager automatically assigns the 'PacketInjectionExperiment'
        label to all EdgeNode windows captured during the run() phase via the
        LabelManager. Dataset archival is performed automatically by the
        DatasetSynchronizer after cleanup() completes.
    """

    def initialize(self) -> None:
        cfg = self.config.get("injection", {})
        self.num_packets = cfg.get("num_packets", 50)
        self.interval_ms = cfg.get("interval_ms", 400)
        self.node_id = cfg.get("fake_node_id", 1)
        self.vib_mult = cfg.get("fake_vibration_multiplier", 5.0)
        self.target_ip = self.config.get("server_ip", "127.0.0.1")
        self.target_port = self.config.get("server_port", 9000)
        self.sent = 0
        self.errors = 0
        self.sock = None
        self._log_initialized()

    def run(self) -> None:
        self._log_started()
        
        pre_attack = self.experiment_config.get("pre_attack_duration", 5.0)
        self.logger.info(f"[{self.name}] Observing pre-attack baseline for {pre_attack}s...")
        time.sleep(pre_attack)

        attack_duration = self.experiment_config.get("attack_duration", 30.0)
        self.logger.info(f"[{self.name}] INJECTION ATTACK — {self.num_packets} fake packets, node_id={self.node_id}, "
                         f"vibration×{self.vib_mult} against {self.target_ip}:{self.target_port}")
        
        try:
            self.sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            self.sock.settimeout(5.0)
            self.sock.connect((self.target_ip, self.target_port))
            self.sock.settimeout(None)
            src_ip, src_port = self.sock.getsockname()
            self._register_attacker_flow(src_ip, src_port, self.target_ip, self.target_port)
        except Exception as e:
            self.logger.error(f"Cannot connect to {self.target_ip}:{self.target_port} — {e}")
            return

        interval_sec = self.interval_ms / 1000.0
        base_normal_rms = 0.5   # typical normal vibration RMS (g)

        start_time = time.time()
        i = 0

        while time.time() - start_time < attack_duration:
            rms_x = base_normal_rms * self.vib_mult * (1.0 + random.uniform(-0.1, 0.1))
            rms_y = base_normal_rms * self.vib_mult * (1.0 + random.uniform(-0.1, 0.1))
            rms_z = base_normal_rms * self.vib_mult * (1.0 + random.uniform(-0.1, 0.1))

            mean_x = rms_x * 0.1
            mean_y = rms_y * 0.1
            mean_z = rms_z * 0.1

            std_x  = rms_x * 0.9
            std_y  = rms_y * 0.9
            std_z  = rms_z * 0.9

            max_x  =  rms_x * 1.8
            max_y  =  rms_y * 1.8
            max_z  =  rms_z * 1.8

            min_x  = -rms_x * 1.6
            min_y  = -rms_y * 1.6
            min_z  = -rms_z * 1.6

            p2p_x  = max_x - min_x
            p2p_y  = max_y - min_y
            p2p_z  = max_z - min_z

            skew_x = random.uniform(-0.5, 0.5)
            skew_y = random.uniform(-0.5, 0.5)
            skew_z = random.uniform(-0.5, 0.5)

            kurt_x = random.uniform(3.0, 6.0)
            kurt_y = random.uniform(3.0, 6.0)
            kurt_z = random.uniform(3.0, 6.0)

            # Generate a completely malformed packet
            payload = _build_malformed_packet()

            try:
                self.sock.sendall(payload)
                self.sock.setblocking(False)
                try:
                    self.sock.recv(1)
                except BlockingIOError:
                    pass
                self.sock.setblocking(True)
                self.sent += 1
            except Exception as e:
                self.errors += 1
                self.logger.error(f"[{self.name}] Failed to send malformed packet: {e}")

            time.sleep(interval_sec)
            i += 1
        
        post_attack = self.experiment_config.get("post_attack_duration", 5.0)
        self.logger.info(f"[{self.name}] Observing post-attack baseline for {post_attack}s...")
        time.sleep(post_attack)
        
        self._log_completed()

    def cleanup(self) -> None:
        if self.sock:
            self.sock.close()
        self._clear_attacker_flows()
        self.logger.info(f"[{self.name}] Malformed Packet Injection complete. Sent: {self.sent}, Errors: {self.errors}")
        self._log_cleaned_up()
